if __name__ == "__main__":
    sea = Ocean(Hs=1.5, Tp=6.0, seed=42)
    print("PM spectrum discrete components n =", sea.n_freq)
    print("omega range =", sea.omega[0], "..", sea.omega[-1], "rad/s")
    stats = sea.statistics()
    for k, v in stats.items():
        print(f"  {k:15s}: {v:.3f}")
